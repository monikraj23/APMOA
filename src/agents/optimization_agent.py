"""
APMOA - Optimization Agent

Generates deterministic, rule-based optimization recommendations
from bottleneck, deviation, rework, transition, and process-model
analysis.

This is intentionally rule-based for the current APMOA prototype.

Input:
    Bottleneck / deviation analysis results.

Output:
    Structured optimization recommendations.

The output is designed to be consumed by:
    - Orchestrator
    - Reporting layer
    - Final optimization stage
    - Experimental evaluation

Supported recommendation categories:

    1. Bottleneck Reduction
    2. Deviation Investigation
    3. Rework Reduction
    4. Transition Improvement
    5. Process Simplification
    6. General Process Improvement
"""

from __future__ import annotations

from typing import Any, Dict, Iterable, List, Optional
import math


class OptimizationAgent:
    """
    Deterministic rule-based optimization recommendation agent.

    The agent does NOT change the process model itself.

    It analyzes evidence generated by the Bottleneck & Deviation
    Analysis Agent and converts that evidence into structured
    recommendations.
    """

    # =========================================================
    # CONFIGURATION
    # =========================================================

    DEFAULT_MAX_RECOMMENDATIONS = 10

    BOTTLENECK_HIGH_THRESHOLD = 0.75
    BOTTLENECK_MEDIUM_THRESHOLD = 0.50

    DEVIATION_HIGH_THRESHOLD = 0.75
    DEVIATION_MEDIUM_THRESHOLD = 0.50

    REWORK_HIGH_THRESHOLD = 0.50

    # =========================================================
    # INITIALIZATION
    # =========================================================

    def __init__(
        self,
        max_recommendations: int = DEFAULT_MAX_RECOMMENDATIONS,
    ) -> None:
        """
        Initialize the Optimization Agent.

        Parameters
        ----------
        max_recommendations:
            Maximum number of recommendations returned.
        """

        self.max_recommendations = max(
            1,
            int(max_recommendations),
        )

        self.last_result: Optional[
            Dict[str, Any]
        ] = None

    # =========================================================
    # SAFE HELPERS
    # =========================================================

    @staticmethod
    def _safe_float(
        value: Any,
        default: float = 0.0,
    ) -> float:
        """
        Safely convert a value to float.
        """

        try:
            result = float(value)

            if math.isnan(result):
                return default

            if math.isinf(result):
                return default

            return result

        except (
            TypeError,
            ValueError,
        ):
            return default

    @staticmethod
    def _safe_int(
        value: Any,
        default: int = 0,
    ) -> int:
        """
        Safely convert a value to int.
        """

        try:
            return int(value)

        except (
            TypeError,
            ValueError,
        ):
            return default

    @staticmethod
    def _normalize_text(
        value: Any,
    ) -> str:
        """
        Normalize arbitrary values into readable text.
        """

        if value is None:
            return ""

        return str(value).strip()

    @staticmethod
    def _get(
        data: Any,
        *keys: str,
        default: Any = None,
    ) -> Any:
        """
        Retrieve the first available key from a dictionary-like
        object.
        """

        if data is None:
            return default

        for key in keys:

            try:

                if isinstance(data, dict):

                    value = data.get(key)

                else:

                    value = getattr(
                        data,
                        key,
                        None,
                    )

                if value is not None:
                    return value

            except Exception:
                continue

        return default

    @staticmethod
    def _as_list(
        value: Any,
    ) -> List[Any]:
        """
        Convert a value into a list safely.
        """

        if value is None:
            return []

        if isinstance(value, list):
            return value

        if isinstance(value, tuple):
            return list(value)

        if isinstance(value, set):
            return list(value)

        if isinstance(value, Iterable):

            if isinstance(value, (str, bytes)):
                return [value]

            try:
                return list(value)

            except Exception:
                return [value]

        return [value]

    # =========================================================
    # PRIORITY
    # =========================================================

    @classmethod
    def _priority_from_score(
        cls,
        score: float,
        category: str = "Bottleneck Reduction",
    ) -> str:
        """
        Convert a category-specific evidence score into priority.
        """

        score = cls._safe_float(score)
        category = cls._normalize_text(category).lower()

        if "deviation" in category:
            high = cls.DEVIATION_HIGH_THRESHOLD
            medium = cls.DEVIATION_MEDIUM_THRESHOLD
        elif "rework" in category:
            high = cls.REWORK_HIGH_THRESHOLD
            medium = 0.25
        else:
            high = cls.BOTTLENECK_HIGH_THRESHOLD
            medium = cls.BOTTLENECK_MEDIUM_THRESHOLD

        if score >= high:
            return "HIGH"

        if score >= medium:
            return "MEDIUM"

        return "LOW"

    # =========================================================
    # RECOMMENDATION ID
    # =========================================================

    @staticmethod
    def _recommendation_id(
        prefix: str,
        number: int,
    ) -> str:
        """
        Generate deterministic recommendation IDs.
        """

        return f"{prefix}-{number:03d}"

    # =========================================================
    # BOTTLENECK RECOMMENDATIONS
    # =========================================================

    def _bottleneck_recommendations(
        self,
        bottlenecks: List[Any],
        recommendations: List[Dict[str, Any]],
    ) -> None:
        """
        Generate recommendations from bottleneck information.
        """

        for bottleneck in bottlenecks:

            if len(recommendations) >= self.max_recommendations:
                return

            activity = self._get(
                bottleneck,
                "activity",
                "name",
                "activity_name",
                "affected_activity",
                default="Unknown activity",
            )

            activity = self._normalize_text(
                activity
            )

            score = self._get(
                bottleneck,
                "score",
                "bottleneck_score",
                "severity",
                default=0.0,
            )

            score = self._safe_float(
                score
            )

            priority = self._priority_from_score(
                score
            )

            recommendations.append(
                {
                    "recommendation_id":
                        self._recommendation_id(
                            "BOT",
                            len(recommendations) + 1,
                        ),

                    "category":
                        "Bottleneck Reduction",

                    "priority":
                        priority,

                    "affected_activity":
                        activity,

                    "problem": (
                        f"{activity} is identified as a "
                        "potential process bottleneck."
                    ),

                    "evidence": [
                        f"Bottleneck score: {score:.2f}",
                        (
                            "The activity was identified "
                            "by bottleneck analysis."
                        ),
                    ],

                    "impact": (
                        "The bottleneck may contribute to "
                        "longer process execution time, "
                        "waiting, or reduced throughput."
                    ),

                    "recommendation": (
                        f"Investigate the waiting and "
                        f"processing time associated with "
                        f"'{activity}'. Consider workload "
                        "balancing, resource reassignment, "
                        "or parallel execution where "
                        "business rules permit."
                    ),

                    "score":
                        score,
                }
            )

    # =========================================================
    # DEVIATION RECOMMENDATIONS
    # =========================================================

    def _deviation_recommendations(
        self,
        deviations: List[Any],
        recommendations: List[Dict[str, Any]],
    ) -> None:
        """
        Generate recommendations from process deviations.
        """

        for deviation in deviations:

            if len(recommendations) >= self.max_recommendations:
                return

            deviation_score = self._get(
                deviation,
                "deviation",
                "deviation_score",
                "score",
                "severity",
                default=0.0,
            )

            deviation_score = self._safe_float(
                deviation_score
            )

            cases = self._get(
                deviation,
                "cases",
                "case_count",
                "count",
                "occurrences",
                default=0,
            )

            cases = self._safe_int(
                cases
            )

            priority = self._priority_from_score(
                deviation_score
            )

            recommendations.append(
                {
                    "recommendation_id":
                        self._recommendation_id(
                            "DEV",
                            len(recommendations) + 1,
                        ),

                    "category":
                        "Deviation Correction",

                    "priority":
                        priority,

                    "affected_activity":
                        "Process Variant",

                    "problem": (
                        "A process variant differs "
                        "substantially from the dominant "
                        "observed variant."
                    ),

                    "evidence": [
                        (
                            f"Deviation score: "
                            f"{deviation_score:.2f}"
                        ),
                        (
                            f"Cases affected: "
                            f"{cases}"
                        ),
                    ],

                    "impact": (
                        "The deviation may indicate "
                        "exceptional handling, inconsistent "
                        "execution, or an opportunity for "
                        "process standardization."
                    ),

                    "recommendation": (
                        "Investigate the affected process "
                        "variant and determine whether it "
                        "represents a legitimate business "
                        "exception or an undesirable "
                        "deviation."
                    ),

                    "score":
                        deviation_score,

                    "affected_cases":
                        cases,
                }
            )

    # =========================================================
    # REWORK RECOMMENDATIONS
    # =========================================================

    def _rework_recommendations(
        self,
        rework_activities: List[Any],
        recommendations: List[Dict[str, Any]],
    ) -> None:
        """
        Generate recommendations for activities with rework.
        """

        for item in rework_activities:

            if len(recommendations) >= self.max_recommendations:
                return

            if isinstance(item, dict):

                activity = self._get(
                    item,
                    "activity",
                    "name",
                    "activity_name",
                    default="Unknown activity",
                )

                count = self._get(
                    item,
                    "count",
                    "rework_count",
                    "occurrences",
                    default=0,
                )

                score = self._get(
                    item,
                    "score",
                    "rework_score",
                    default=0.0,
                )

            else:

                activity = item
                count = 0
                score = 0.0

            activity = self._normalize_text(
                activity
            )

            count = self._safe_int(
                count
            )

            score = self._safe_float(
                score
            )

            if score <= 0.0 and count > 0:
                score = min(
                    1.0,
                    count / 10.0,
                )

            priority = self._priority_from_score(
                score
            )

            recommendations.append(
                {
                    "recommendation_id":
                        self._recommendation_id(
                            "REW",
                            len(recommendations) + 1,
                        ),

                    "category":
                        "Rework Reduction",

                    "priority":
                        priority,

                    "affected_activity":
                        activity,

                    "problem": (
                        f"Repeated execution of "
                        f"'{activity}' indicates "
                        "potential rework."
                    ),

                    "evidence": [
                        (
                            f"Observed rework count: "
                            f"{count}"
                        ),
                        (
                            f"Rework severity score: "
                            f"{score:.2f}"
                        ),
                    ],

                    "impact": (
                        "Rework increases process effort, "
                        "cycle time, and resource consumption."
                    ),

                    "recommendation": (
                        f"Investigate the root cause of "
                        f"repeated execution of '{activity}'. "
                        "Consider improving validation, "
                        "approval rules, or upstream data "
                        "quality to reduce unnecessary "
                        "rework."
                    ),

                    "score":
                        score,

                    "rework_count":
                        count,
                }
            )

    # =========================================================
    # TRANSITION RECOMMENDATIONS
    # =========================================================

    def _transition_recommendations(
        self,
        transitions: List[Any],
        recommendations: List[Dict[str, Any]],
    ) -> None:
        """
        Generate recommendations from transition information.
        """

        for transition in transitions:

            if len(recommendations) >= self.max_recommendations:
                return

            source = self._get(
                transition,
                "source",
                "from",
                "from_activity",
                "activity_from",
                default="Unknown",
            )

            target = self._get(
                transition,
                "target",
                "to",
                "to_activity",
                "activity_to",
                default="Unknown",
            )

            frequency = self._get(
                transition,
                "frequency",
                "count",
                "occurrences",
                default=0,
            )

            score = self._get(
                transition,
                "score",
                "transition_score",
                default=0.0,
            )

            source = self._normalize_text(
                source
            )

            target = self._normalize_text(
                target
            )

            frequency = self._safe_int(
                frequency
            )

            score = self._safe_float(
                score
            )

            recommendations.append(
                {
                    "recommendation_id":
                        self._recommendation_id(
                            "TRN",
                            len(recommendations) + 1,
                        ),

                    "category":
                        "Flow Optimization",

                    "priority":
                        self._priority_from_score(
                            score,
                            "Flow Optimization",
                        ),

                    "affected_activity":
                        f"{source} -> {target}",

                    "problem": (
                        f"The transition from "
                        f"'{source}' to '{target}' "
                        "requires investigation."
                    ),

                    "evidence": [
                        (
                            f"Transition frequency: "
                            f"{frequency}"
                        ),
                        (
                            f"Transition score: "
                            f"{score:.2f}"
                        ),
                    ],

                    "impact": (
                        "Frequent or problematic transitions "
                        "may indicate unnecessary handoffs, "
                        "delays, or process complexity."
                    ),

                    "recommendation": (
                        f"Review the transition from "
                        f"'{source}' to '{target}'. "
                        "Assess whether the handoff can "
                        "be simplified, automated, or "
                        "performed in parallel."
                    ),

                    "score":
                        score,

                    "frequency":
                        frequency,
                }
            )

    # =========================================================
    # GENERAL RECOMMENDATION
    # =========================================================

    def _general_recommendation(
        self,
        analysis: Dict[str, Any],
        recommendations: List[Dict[str, Any]],
    ) -> None:
        """
        Add a general process-improvement recommendation when
        insufficient detailed evidence is available.
        """

        if len(recommendations) >= self.max_recommendations:
            return

        bottleneck_count = self._safe_int(
            analysis.get(
                "potential_bottlenecks",
                0,
            )
        )

        deviation_count = self._safe_int(
            analysis.get(
                "potential_deviations",
                0,
            )
        )

        rework_count = self._safe_int(
            analysis.get(
                "activities_with_rework",
                0,
            )
        )

        recommendations.append(
            {
                "recommendation_id":
                    self._recommendation_id(
                        "GEN",
                        len(recommendations) + 1,
                    ),

                "category":
                    "General Process Improvement",

                "priority":
                    "MEDIUM",

                "affected_activity":
                    "Overall Process",

                "problem": (
                    "The process contains multiple "
                    "bottlenecks, deviations, or "
                    "rework indicators."
                ),

                "evidence": [
                    (
                        f"Potential bottlenecks: "
                        f"{bottleneck_count}"
                    ),
                    (
                        f"Potential deviations: "
                        f"{deviation_count}"
                    ),
                    (
                        f"Activities with rework: "
                        f"{rework_count}"
                    ),
                ],

                "impact": (
                    "The combined issues may increase "
                    "cycle time, operational effort, "
                    "and process variability."
                ),

                "recommendation": (
                    "Prioritize the highest-severity "
                    "bottlenecks and rework activities, "
                    "then investigate the most frequent "
                    "process deviations for targeted "
                    "improvement."
                ),

                "score":
                    0.50,
            }
        )

    # =========================================================
    # SORT RECOMMENDATIONS
    # =========================================================

    @staticmethod
    def _sort_recommendations(
        recommendations: List[Dict[str, Any]],
    ) -> List[Dict[str, Any]]:
        """
        Sort recommendations by:

            1. Priority
            2. Score
        """

        priority_order = {
            "HIGH": 3,
            "MEDIUM": 2,
            "LOW": 1,
        }

        return sorted(
            recommendations,
            key=lambda item: (
                priority_order.get(
                    str(
                        item.get(
                            "priority",
                            "LOW",
                        )
                    ).upper(),
                    0,
                ),
                OptimizationAgent._safe_float(
                    item.get(
                        "score",
                        0.0,
                    )
                ),
            ),
            reverse=True,
        )

    # =========================================================
    # MAIN OPTIMIZATION METHOD
    # =========================================================

    def optimize(
        self,
        analysis: Optional[Dict[str, Any]] = None,
        bottleneck_results: Optional[Dict[str, Any]] = None,
        **kwargs: Any,
    ) -> Dict[str, Any]:
        """
        Generate optimization recommendations.

        Parameters
        ----------
        analysis:
            Bottleneck/deviation analysis dictionary.

        bottleneck_results:
            Alias for analysis. Supported for compatibility.

        Returns
        -------
        dict
            Structured optimization result.
        """

        print("\n" + "=" * 60)
        print("APMOA - OPTIMIZATION AGENT")
        print("=" * 60)

        # -----------------------------------------------------
        # Resolve input
        # -----------------------------------------------------

        if analysis is None:
            analysis = bottleneck_results

        if analysis is None:

            analysis = kwargs.get(
                "results"
            )

        if analysis is None:
            analysis = {}

        if not isinstance(
            analysis,
            dict,
        ):
            raise TypeError(
                "Optimization Agent input must be a dictionary."
            )

        print(
            "\nGenerating rule-based optimization recommendations..."
        )

        # -----------------------------------------------------
        # Extract evidence
        # -----------------------------------------------------

        bottlenecks = self._as_list(
            analysis.get(
                "bottlenecks",
                analysis.get(
                    "potential_bottlenecks_list",
                    [],
                ),
            )
        )

        deviations = self._as_list(
            analysis.get(
                "deviations",
                analysis.get(
                    "potential_deviations_list",
                    [],
                ),
            )
        )

        rework = self._as_list(
            analysis.get(
                "rework",
                analysis.get(
                    "rework_activities",
                    analysis.get(
                        "activities_with_rework_list",
                        [],
                    ),
                ),
            )
        )

        transitions = self._as_list(
            analysis.get(
                "transitions",
                analysis.get(
                    "transition_analysis",
                    [],
                ),
            )
        )

        # -----------------------------------------------------
        # Generate recommendations
        # -----------------------------------------------------

        recommendations: List[
            Dict[str, Any]
        ] = []

        print(
            "Analyzing bottlenecks..."
        )
        print(
            "Analyzing deviations..."
        )
        print(
            "Analyzing rework..."
        )
        print(
            "Analyzing transitions..."
        )

        # ---------------------------------------------------------
        # Balanced evidence allocation
        # ---------------------------------------------------------
        # The previous implementation exhausted bottlenecks first.
        # Since max_recommendations defaults to 10, a large
        # bottleneck list could prevent deviations, rework, and
        # transitions from ever reaching the output.
        #
        # Generate one recommendation from each evidence family
        # in round-robin order, then use any remaining capacity to
        # add further findings. This preserves the evidence-driven
        # ranking while ensuring that different process-intelligence
        # signals are represented whenever they are available.

        generators = [
            ("bottleneck", bottlenecks, self._bottleneck_recommendations),
            ("deviation", deviations, self._deviation_recommendations),
            ("rework", rework, self._rework_recommendations),
            ("transition", transitions, self._transition_recommendations),
        ]

        positions = {
            name: 0
            for name, _, _ in generators
        }

        # First pass: one item per available evidence family.
        while (
            len(recommendations) < self.max_recommendations
            and any(
                positions[name] < len(items)
                for name, items, _ in generators
            )
        ):
            added_this_round = False

            for name, items, generator in generators:
                if len(recommendations) >= self.max_recommendations:
                    break

                position = positions[name]

                if position >= len(items):
                    continue

                # Each generator accepts a list, so provide exactly
                # one evidence item during the balanced pass.
                before = len(recommendations)

                generator(
                    items[position:position + 1],
                    recommendations,
                )

                positions[name] += 1

                if len(recommendations) > before:
                    added_this_round = True

            if not added_this_round:
                break

        # -----------------------------------------------------
        # General recommendation
        # -----------------------------------------------------

        if not recommendations:

            self._general_recommendation(
                analysis,
                recommendations,
            )

        # -----------------------------------------------------
        # Sort
        # -----------------------------------------------------

        recommendations = (
            self._sort_recommendations(
                recommendations
            )
        )

        # -----------------------------------------------------
        # Limit
        # -----------------------------------------------------

        recommendations = recommendations[
            : self.max_recommendations
        ]

        # -----------------------------------------------------
        # Re-number after sorting
        # -----------------------------------------------------

        for index, recommendation in enumerate(
            recommendations,
            start=1,
        ):

            category = str(
                recommendation.get(
                    "category",
                    "General",
                )
            ).upper()

            if "BOTTLENECK" in category:
                prefix = "BOT"

            elif "DEVIATION" in category:
                prefix = "DEV"

            elif "REWORK" in category:
                prefix = "REW"

            elif (
                "TRANSITION" in category
                or "FLOW" in category
            ):
                prefix = "TRN"

            else:
                prefix = "GEN"

            recommendation[
                "recommendation_id"
            ] = self._recommendation_id(
                prefix,
                index,
            )

        # -----------------------------------------------------
        # Summary
        # -----------------------------------------------------

        high = sum(
            1
            for item in recommendations
            if str(
                item.get(
                    "priority",
                    "",
                )
            ).upper()
            == "HIGH"
        )

        medium = sum(
            1
            for item in recommendations
            if str(
                item.get(
                    "priority",
                    "",
                )
            ).upper()
            == "MEDIUM"
        )

        low = sum(
            1
            for item in recommendations
            if str(
                item.get(
                    "priority",
                    "",
                )
            ).upper()
            == "LOW"
        )

        result = {
            "status":
                "SUCCESS",

            "recommendations":
                recommendations,

            "recommendation_count":
                len(recommendations),

            "high_priority":
                high,

            "medium_priority":
                medium,

            "low_priority":
                low,

            "input_summary": {
                "events":
                    self._safe_int(
                        analysis.get(
                            "events",
                            0,
                        )
                    ),

                "cases":
                    self._safe_int(
                        analysis.get(
                            "cases",
                            0,
                        )
                    ),

                "activities":
                    self._safe_int(
                        analysis.get(
                            "activities",
                            0,
                        )
                    ),

                "transitions":
                    self._safe_int(
                        analysis.get(
                            "transitions",
                            0,
                        )
                    ),

                "potential_bottlenecks":
                    self._safe_int(
                        analysis.get(
                            "potential_bottlenecks",
                            len(bottlenecks),
                        )
                    ),

                "potential_deviations":
                    self._safe_int(
                        analysis.get(
                            "potential_deviations",
                            len(deviations),
                        )
                    ),

                "activities_with_rework":
                    self._safe_int(
                        analysis.get(
                            "activities_with_rework",
                            len(rework),
                        )
                    ),
            },

            "method":
                "deterministic_rule_based",

            "agent":
                "OptimizationAgent",
        }

        self.last_result = result

        # -----------------------------------------------------
        # Output
        # -----------------------------------------------------

        print("\n" + "-" * 60)
        print("OPTIMIZATION RECOMMENDATION SUMMARY")
        print("-" * 60)

        print(
            f"Recommendations generated : "
            f"{len(recommendations)}"
        )

        print(
            f"High priority             : "
            f"{high}"
        )

        print(
            f"Medium priority           : "
            f"{medium}"
        )

        print(
            f"Low priority              : "
            f"{low}"
        )

        if recommendations:

            print(
                "\nTOP RECOMMENDATIONS"
            )

            print(
                "-" * 60
            )

            for recommendation in recommendations:

                print(
                    f"{recommendation['recommendation_id']}"
                    f" | "
                    f"{recommendation['priority']:<6}"
                    f" | "
                    f"{recommendation['category']}"
                )

                print(
                    f"  Activity : "
                    f"{recommendation['affected_activity']}"
                )

                print(
                    f"  Action   : "
                    f"{recommendation['recommendation']}"
                )

        print(
            "\n" + "=" * 60
        )

        print(
            "OPTIMIZATION AGENT COMPLETED"
        )

        print(
            "=" * 60
        )

        return result

